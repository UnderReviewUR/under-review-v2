#!/usr/bin/env node
/**
 * Pull all 32 BDL NFL GOAT rosters and write api/data/nflBdlRosterSnapshot.js
 * so Ask + identity never lose to stale static PHI/GB assignments.
 *
 *   node --env-file=.env scripts/sync-nfl-bdl-rosters.mjs
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { inferNflSeasonYear } from "../shared/bdlSeasonDefaults.js";
import { normalizePlayerKey } from "../shared/nflAskPropTrim.js";
import {
  fetchNflBdlTeams,
  getNflBdlApiKey,
  nflBdlFetch,
  normalizeNflBdlRosterRows,
} from "../api/_nflBdl.js";

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const season = Number(process.argv.includes("--season")
  ? process.argv[process.argv.indexOf("--season") + 1]
  : inferNflSeasonYear());
const paceMs = Number(process.env.NFL_BDL_ROSTER_PACE_MS || 600);

async function fetchRosterWithRetry(teamId, abbr) {
  for (let attempt = 0; attempt < 6; attempt++) {
    const res = await nflBdlFetch(`/teams/${teamId}/roster`, { season }, { timeoutMs: 25000 });
    if (res.ok) {
      const rows = Array.isArray(res.data?.data) ? res.data.data : [];
      return { ok: true, rows: normalizeNflBdlRosterRows(rows, abbr), status: res.status };
    }
    if (res.status === 429) {
      const wait = 15000 * (attempt + 1);
      console.error(JSON.stringify({ event: "roster_429", abbr, wait, attempt }));
      await sleep(wait);
      continue;
    }
    return { ok: false, rows: [], status: res.status, error: res.error };
  }
  return { ok: false, rows: [], status: 429, error: "rate_limited" };
}

async function main() {
  if (!getNflBdlApiKey()) {
    console.error(JSON.stringify({ ok: false, error: "BALLDONTLIE_API_KEY missing" }));
    process.exit(1);
  }

  const teams = await fetchNflBdlTeams();
  if (!teams.length) {
    console.error(JSON.stringify({ ok: false, error: "no BDL teams" }));
    process.exit(1);
  }

  /** @type {Record<string, Array<{ name: string, position: string|null, playerId: unknown }>>} */
  const rostersByTeam = {};
  /** @type {Record<string, string>} */
  const playerTeamByName = {};
  const errors = [];

  for (const team of teams) {
    const abbr = String(team?.abbreviation || "").toUpperCase();
    const teamId = Number(team?.id);
    if (!abbr || !Number.isFinite(teamId)) continue;
    const got = await fetchRosterWithRetry(teamId, abbr);
    if (!got.ok) {
      errors.push({ abbr, status: got.status, error: got.error });
    } else if (got.rows.length) {
      rostersByTeam[abbr] = got.rows.map((r) => ({
        name: r.name,
        position: r.position,
        playerId: r.playerId,
      }));
      for (const r of got.rows) {
        const key = normalizePlayerKey(r.name);
        if (key && abbr) playerTeamByName[key] = abbr;
      }
    }
    console.error(JSON.stringify({ event: "roster", abbr, count: got.rows.length, ok: got.ok }));
    await sleep(paceMs);
  }

  const teamCount = Object.keys(rostersByTeam).length;
  const playerCount = Object.keys(playerTeamByName).length;
  const ne = (rostersByTeam.NE || []).map((r) => r.name);
  const snapshot = {
    season,
    fetchedAt: new Date().toISOString(),
    teamCount,
    playerCount,
    playerTeamByName,
    rostersByTeam,
  };

  mkdirSync(resolve("api/data"), { recursive: true });
  const outJs = resolve("api/data/nflBdlRosterSnapshot.js");
  const body = `/* Generated by scripts/sync-nfl-bdl-rosters.mjs — do not edit by hand. */
export const NFL_BDL_ROSTER_SNAPSHOT = ${JSON.stringify(snapshot, null, 2)};
`;
  writeFileSync(outJs, body, "utf8");

  const report = {
    ok: teamCount >= 28,
    season,
    teamCount,
    playerCount,
    errors,
    neCount: ne.length,
    neHasAjBrown: Boolean(playerTeamByName["aj brown"] === "NE"),
    neHasDoubs: Boolean(playerTeamByName["romeo doubs"] === "NE"),
    ajBrownTeam: playerTeamByName["aj brown"] || null,
    doubsTeam: playerTeamByName["romeo doubs"] || null,
    outJs,
  };
  console.log(JSON.stringify(report, null, 2));
  if (!report.ok) process.exit(1);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
